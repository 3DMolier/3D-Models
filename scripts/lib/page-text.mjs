/*
 * page-text.mjs - собственный текст карточки, без чужих названий.
 *
 * ЗАЧЕМ. Проверки по словам нельзя гонять по всей разметке страницы. На карточке
 * дальномера Makita нашлось слово «battlefield» - и это было НЕ обещание для
 * боевого применения, а название соседней модели в блоке «Related 3D Models»
 * плюс то же слово в адресе её превью. Такие ложные тревоги уже случались с
 * блоком версий и с адресами картинок.
 *
 * Здесь остаётся только то, что карточка говорит О СЕБЕ: выбрасываем блоки
 * «похожие» и «версии», разметку JSON-LD, а затем все теги вместе с атрибутами.
 */

/** Видимый текст карточки без блоков с чужими названиями. */
export function proseOf(html) {
  let s = String(html);
  s = s.replace(/<section class="mp-related-section[\s\S]*?<\/section>/g, ' ');
  s = s.replace(/<script[\s\S]*?<\/script>/g, ' ');
  // Блок ключевых слов - это список из исходных данных TurboSquid, а не то,
  // что карточка обещает. У «Helicopter Debris» там стоит «battlefield», и
  // проверка засчитывала это как обещание боевого применения.
  s = s.replace(/<div class="mp-kw-block"[\s\S]*?<\/div>/g, ' ');
  s = s.replace(/<[^>]*>/g, ' ');
  return s.replace(/\s+/g, ' ');
}
